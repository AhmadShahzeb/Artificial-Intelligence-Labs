# For loop

# List Iteration
print("Lists\n")
list = ["first", "second", "third"]
for i in list:
    print(i)


# Tuple Iteration
print("\nTuple\n")
tup = ("first", "second", "third")
for i in tup:
    print(i)

# String
print("\nString\n")
str = "Artificial"
for i in str:
    print(i)

# Iterate by index
print("\nindex iteration\n")
length = len(list)
for i in range(length):
    print(list[i])